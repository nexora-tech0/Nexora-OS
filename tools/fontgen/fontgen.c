/*
 * Nexora OS - tools/fontgen/fontgen.c   (host tool)
 * Rasterizes printable ASCII from a TrueType font into a C source file holding a BOOT_FONT
 * (see include/bootfont.h): 8-bit coverage bitmaps, 26.6 advances and kerning pairs.
 *
 *   fontgen <font.ttf> <em-pixels> <symbol> <display-name> <out.c>
 *
 * Coverage gets a mild gamma lift so light-on-dark text does not look thin, since the kernel
 * blends in sRGB space.
 */
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define FIRST_CHAR 32
#define LAST_CHAR 126
#define GLYPH_COUNT (LAST_CHAR - FIRST_CHAR + 1)
#define COVERAGE_GAMMA 1.3

static unsigned char *ReadFile(const char *Path, size_t *Size)
{
    FILE *f = fopen(Path, "rb");
    if (!f) {
        perror(Path);
        exit(1);
    }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *Data = malloc((size_t)n);
    if (!Data || fread(Data, 1, (size_t)n, f) != (size_t)n) {
        fprintf(stderr, "fontgen: cannot read %s\n", Path);
        exit(1);
    }
    fclose(f);
    *Size = (size_t)n;
    return Data;
}

static long Round26_6(double Pixels)
{
    return lround(Pixels * 64.0);
}

int main(int argc, char **argv)
{
    if (argc != 6) {
        fprintf(stderr, "usage: fontgen <font.ttf> <em-pixels> <symbol> <display-name> <out.c>\n");
        return 2;
    }
    const char *FontPath = argv[1];
    int EmPixels = atoi(argv[2]);
    const char *Symbol = argv[3];
    const char *DisplayName = argv[4];
    const char *OutPath = argv[5];

    size_t FontSize;
    unsigned char *FontData = ReadFile(FontPath, &FontSize);
    stbtt_fontinfo Font;
    if (!stbtt_InitFont(&Font, FontData, stbtt_GetFontOffsetForIndex(FontData, 0))) {
        fprintf(stderr, "fontgen: %s is not a usable TrueType font\n", FontPath);
        return 1;
    }

    float Scale = stbtt_ScaleForMappingEmToPixels(&Font, (float)EmPixels);
    int Ascent, Descent, LineGap;
    stbtt_GetFontVMetrics(&Font, &Ascent, &Descent, &LineGap);
    int AscentPx = (int)ceil(Ascent * Scale);
    int DescentPx = (int)ceil(-Descent * Scale);
    int LineHeightPx = (int)lround((Ascent - Descent + LineGap) * Scale);

    unsigned char Gamma[256];
    for (int i = 0; i < 256; i++)
        Gamma[i] = (unsigned char)lround(255.0 * pow(i / 255.0, 1.0 / COVERAGE_GAMMA));

    FILE *Out = fopen(OutPath, "w");
    if (!Out) {
        perror(OutPath);
        return 1;
    }
    fprintf(Out, "/* Generated by tools/fontgen from %s at %d px. Do not edit. */\n", FontPath, EmPixels);
    fprintf(Out, "#include \"bootfont.h\"\n\n");

    struct {
        long Advance;
        int X0, Y0, W, H;
        unsigned Offset;
    } Glyphs[GLYPH_COUNT];

    fprintf(Out, "static const uint8_t %sBitmap[] = {\n", Symbol);
    unsigned Offset = 0;
    for (int c = FIRST_CHAR; c <= LAST_CHAR; c++) {
        int i = c - FIRST_CHAR;
        int AdvanceWidth, LeftBearing;
        stbtt_GetCodepointHMetrics(&Font, c, &AdvanceWidth, &LeftBearing);
        Glyphs[i].Advance = Round26_6(AdvanceWidth * Scale);

        int x0, y0, x1, y1;
        stbtt_GetCodepointBitmapBox(&Font, c, Scale, Scale, &x0, &y0, &x1, &y1);
        int w = x1 - x0, h = y1 - y0;
        if (w <= 0 || h <= 0 || c == ' ') {
            w = h = 0;
        }
        Glyphs[i].X0 = x0;
        Glyphs[i].Y0 = y0;
        Glyphs[i].W = w;
        Glyphs[i].H = h;
        Glyphs[i].Offset = Offset;

        if (w && h) {
            unsigned char *Pixels = calloc((size_t)w * (size_t)h, 1);
            stbtt_MakeCodepointBitmap(&Font, Pixels, w, h, w, Scale, Scale, c);
            fprintf(Out, "    /* '%s%c' */", (c == '\\' || c == '\'') ? "\\" : "", c);
            for (int p = 0; p < w * h; p++) {
                if (p % 24 == 0)
                    fprintf(Out, "\n   ");
                fprintf(Out, " %3u,", Gamma[Pixels[p]]);
            }
            fprintf(Out, "\n");
            free(Pixels);
            Offset += (unsigned)(w * h);
        }
    }
    if (Offset == 0)
        fprintf(Out, "    0,\n");
    fprintf(Out, "};\n\n");

    fprintf(Out, "static const BOOT_GLYPH %sGlyphs[BOOTFONT_GLYPH_COUNT] = {\n", Symbol);
    for (int i = 0; i < GLYPH_COUNT; i++) {
        fprintf(Out, "    {%ld, %d, %d, %d, %d, %u},\n", Glyphs[i].Advance, Glyphs[i].X0, Glyphs[i].Y0,
                Glyphs[i].W, Glyphs[i].H, Glyphs[i].Offset);
    }
    fprintf(Out, "};\n\n");

    /* Kerning pairs, emitted in (Left, Right) order for binary search. */
    fprintf(Out, "static const BOOT_KERN_PAIR %sKerning[] = {\n", Symbol);
    unsigned KernCount = 0;
    for (int l = FIRST_CHAR; l <= LAST_CHAR; l++) {
        for (int r = FIRST_CHAR; r <= LAST_CHAR; r++) {
            int Kern = stbtt_GetCodepointKernAdvance(&Font, l, r);
            long Adjust = Round26_6(Kern * Scale);
            if (Adjust != 0) {
                fprintf(Out, "    {%d, %d, %ld},\n", l, r, Adjust);
                KernCount++;
            }
        }
    }
    if (KernCount == 0)
        fprintf(Out, "    {0, 0, 0},\n");
    fprintf(Out, "};\n\n");

    fprintf(Out, "const BOOT_FONT %s = {\n", Symbol);
    fprintf(Out, "    .Name = \"%s\",\n", DisplayName);
    fprintf(Out, "    .PixelSize = %d,\n", EmPixels);
    fprintf(Out, "    .Ascent = %d,\n", AscentPx);
    fprintf(Out, "    .Descent = %d,\n", DescentPx);
    fprintf(Out, "    .LineHeight = %d,\n", LineHeightPx);
    fprintf(Out, "    .Glyphs = %sGlyphs,\n", Symbol);
    fprintf(Out, "    .Kerning = %sKerning,\n", Symbol);
    fprintf(Out, "    .KerningCount = %u,\n", KernCount);
    fprintf(Out, "    .Bitmap = %sBitmap,\n", Symbol);
    fprintf(Out, "};\n");
    fclose(Out);

    fprintf(stderr, "fontgen: %s -> %s (%u bitmap bytes, %u kerning pairs)\n", DisplayName, OutPath,
            Offset, KernCount);
    free(FontData);
    return 0;
}
